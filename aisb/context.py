"""`aisb context <target|all>`: keep an AI tool's context lean by writing its ignore file (only when asked)."""
from __future__ import annotations

import os

from .common import MARK_HASH, dump_json, parse_jsonc, read_text
from .manifest import Manifest, Writer
from .targets import IGNORE_DEFAULT_GROUPS, IGNORE_GROUPS, TARGETS, parse_tool_list, resolve


def patterns_for(groups, extra):
    out = []
    for g in groups:
        for pat in IGNORE_GROUPS.get(g, []):
            if pat not in out:
                out.append(pat)
    for pat in extra or []:
        if pat and pat not in out:
            out.append(pat)
    return out


def _gitignore_block(groups, extra):
    lines = ["# Generated by `aisb context` - excludes dependency, build, cache and secret files from the AI's context.",
             "# Groups: %s. Edit freely outside the markers; re-run `aisb context <tool>` to refresh this block." % ", ".join(groups)]
    for g in groups:
        pats = IGNORE_GROUPS.get(g, [])
        if pats:
            lines.append("")
            lines.append("# -- %s" % g)
            lines.extend(pats)
    if extra:
        lines.append("")
        lines.append("# -- extra")
        lines.extend(extra)
    return "\n".join(lines)


def _deny_rules_claude(groups, extra):
    """Claude Code has no ignore file: exclusions are permissions.deny Read(...) rules (gitignore-style patterns)."""
    rules = []
    for pat in patterns_for(groups, extra):
        if pat.startswith("!"):
            continue
        p = pat
        if p.endswith("/"):
            p = p + "**"
        elif "/" not in p and not p.startswith("*"):
            p = "**/" + p
        rules.append("Read(%s)" % p)
    return rules


def cmd_context(root, host, log, args):
    m = Manifest(root)
    groups = [g.strip() for g in (args.groups or ",".join(IGNORE_DEFAULT_GROUPS)).split(",") if g.strip()]
    unknown = [g for g in groups if g not in IGNORE_GROUPS]
    if unknown:
        log.fail("unknown groups: %s (available: %s)" % (", ".join(unknown), ", ".join(IGNORE_GROUPS)))
        return 2
    if args.target == "all":
        tids = m.data.get("tools") if m.exists else list(TARGETS.keys())
    else:
        res = parse_tool_list(args.target)
        if isinstance(res, tuple):
            log.fail("unknown target %s (run `aisb targets`)" % ", ".join(res[1]))
            return 2
        tids = res
    w = Writer(root, m, log, dry_run=args.dry_run)
    block = _gitignore_block(groups, args.add)
    written = 0
    for tid in tids:
        t = TARGETS[tid]
        ign = t.get("ignore") or {}
        style = ign.get("style")
        if style == "gitignore" and ign.get("file"):
            files = [ign["file"]] + list((ign.get("extra") or {}).keys())
            for fn in files:
                w.put_block(fn, block, MARK_HASH, label="%s  (%s)" % (fn, t["title"]))
                written += 1
            if ign.get("note"):
                log.info("%-12s %s" % (tid, ign["note"]))
        elif style == "claude-deny":
            rules = _deny_rules_claude(groups, args.add)
            w.merge_json(".claude/settings.json", {"permissions": {"deny": rules}}, label=".claude/settings.json  (permissions.deny Read rules = Claude Code's ignore mechanism)")
            written += 1
            log.info("%-12s %d Read(...) deny rules added (Claude Code has no ignore file; .gitignore only affects the @ picker)" % (tid, len(rules)))
        elif style == "vscode-settings":
            ex = {}
            for pat in patterns_for(groups, args.add):
                if pat.startswith("!"):
                    continue
                key = "**/" + pat.rstrip("/") if "/" not in pat.rstrip("/") else pat.rstrip("/")
                ex[key] = True
            w.merge_json(".vscode/settings.json", {"files.exclude": {k: v for k, v in ex.items() if not k.endswith((".env", ".env.*"))},
                                                   "search.exclude": ex, "files.watcherExclude": {k + "/**": True for k in ex if not k.startswith("**/*.")}},
                         label=".vscode/settings.json  (files/search/watcher excludes)")
            written += 1
        elif style == "zed-settings":
            pats = [p for p in patterns_for(groups, args.add) if not p.startswith("!")]
            w.merge_json(".zed/settings.json", {"file_scan_exclusions": ["**/" + p.rstrip("/") if "/" not in p.rstrip("/") else p.rstrip("/") for p in pats],
                                                "private_files": ["**/.env*", "**/*.pem", "**/*.key", "**/*.p12", "**/*.pfx", "**/id_rsa", "**/id_ed25519"]},
                         label=".zed/settings.json  (file_scan_exclusions, private_files)")
            written += 1
        else:
            log.info("%-12s no project-level ignore file: %s" % (tid, ign.get("note") or "not supported by this tool"))
    if not args.dry_run and m.exists:
        m.save()
    if written:
        log.done("context    %d file(s) updated for %s. Nothing else changed; the AI tools pick this up on their next scan." % (written, ", ".join(tids)))
    if "antigravity" in tids:
        log.info("antigravity Strict Mode respects .gitignore officially; make sure node_modules/, dist/, build/ are also in .gitignore.")
    _ = host, dump_json, parse_jsonc, read_text, resolve, os
    return 0
